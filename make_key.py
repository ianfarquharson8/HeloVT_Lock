"""Create the secret key and the unique Bluetooth name for one lock.

Run:  python make_key.py            (keeps an existing key and name; adds a name if missing)
      python make_key.py --force    (new key and name: re-upload the firmware afterwards)

Writes:
  lock_key.txt             - line 1: the key as hex (paste it into the web app),
                             line 2: the lock's name, e.g. Helo-7F3A. Read by laptop_app.py.
  xiao_led_ble/secret.h    - the same key and name for the firmware
Both files are in .gitignore. Never commit them or share the key.
Each lock needs its own run of this script (its own key and name).
"""

import secrets
import sys
from pathlib import Path

HERE = Path(__file__).parent
KEY_FILE = HERE / "lock_key.txt"
HEADER_FILE = HERE / "xiao_led_ble" / "secret.h"
NAME_PREFIX = "Helo-"


def main():
    key = name = None
    if KEY_FILE.exists() and "--force" not in sys.argv:
        lines = KEY_FILE.read_text().split()
        key = bytes.fromhex(lines[0])
        name = lines[1] if len(lines) > 1 else None
    elif HEADER_FILE.exists() and "--force" not in sys.argv:
        sys.exit(f"{HEADER_FILE.name} exists without {KEY_FILE.name}. Use --force to make a new key "
                 "(the board then needs the firmware re-uploaded).")

    if key is None:
        key = secrets.token_bytes(32)
    if name is None:
        name = NAME_PREFIX + secrets.token_hex(2).upper()

    KEY_FILE.write_text(f"{key.hex()}\n{name}\n")
    HEADER_FILE.write_text(
        "// Generated by make_key.py. Keep secret, do not commit.\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        f'#define LOCK_NAME "{name}"\n\n'
        "const uint8_t LOCK_KEY[32] = {\n    "
        + ", ".join(f"0x{b:02x}" for b in key[:16]) + ",\n    "
        + ", ".join(f"0x{b:02x}" for b in key[16:]) + "\n};\n"
    )
    print(f"Wrote {KEY_FILE.name} and {HEADER_FILE.relative_to(HERE)} for lock {name}")
    print("Upload the firmware again, and paste this key into the web app:")
    print(key.hex())


if __name__ == "__main__":
    main()
