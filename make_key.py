"""Create the secret key shared by the lock and the apps.

Run:  python make_key.py            (refuses to replace an existing key)
      python make_key.py --force    (new key: re-upload the firmware afterwards)

Writes:
  lock_key.txt             - the key as hex, read by laptop_app.py (paste it into the web app too)
  xiao_led_ble/secret.h    - the same key for the firmware
Both files are in .gitignore. Never commit them or share the key.
"""

import secrets
import sys
from pathlib import Path

HERE = Path(__file__).parent
KEY_FILE = HERE / "lock_key.txt"
HEADER_FILE = HERE / "xiao_led_ble" / "secret.h"


def main():
    if (KEY_FILE.exists() or HEADER_FILE.exists()) and "--force" not in sys.argv:
        sys.exit("A key already exists. Use --force to replace it "
                 "(the board then needs the firmware re-uploaded).")

    key = secrets.token_bytes(32)
    KEY_FILE.write_text(key.hex() + "\n")
    HEADER_FILE.write_text(
        "// Generated by make_key.py. Keep secret, do not commit.\n"
        "#pragma once\n"
        "#include <stdint.h>\n\n"
        "const uint8_t LOCK_KEY[32] = {\n    "
        + ", ".join(f"0x{b:02x}" for b in key[:16]) + ",\n    "
        + ", ".join(f"0x{b:02x}" for b in key[16:]) + "\n};\n"
    )
    print(f"Wrote {KEY_FILE.name} and {HEADER_FILE.relative_to(HERE)}")
    print("Upload the firmware again, and paste this key into the web app:")
    print(key.hex())


if __name__ == "__main__":
    main()
